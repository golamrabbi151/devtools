"""Tool abstraction: every tool is a small spec + handler registered here."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable

from markupsafe import Markup


class ToolError(Exception):
    """Expected, user-facing error (bad input). Message is safe to display."""


@dataclass(frozen=True)
class Field:
    name: str
    label: str
    kind: str = "textarea"            # textarea | text | number | select | file | checkbox
    options: tuple = ()               # for select: ((value, label), ...)
    default: str = ""                 # checkbox: "on" means checked by default
    placeholder: str = ""
    required: bool = False
    accept: str = ""                  # for file inputs
    max_len: int | None = None
    lo: int | None = None             # number inputs: allowed range
    hi: int | None = None
    upload: str = ""                  # file inputs: screening profile in app/uploads.py (xlsx | image | cert)


@dataclass(frozen=True)
class Action:
    name: str
    label: str
    primary: bool = False


@dataclass
class Result:
    output: str = ""                  # plain text (what the Copy button copies)
    image: str = ""                   # data: URI generated by us (PNG)
    notes: list = field(default_factory=list)
    html: Markup | None = None        # optional highlighted rendering of `output`
                                      # (must be built with app.highlight: escaped spans only)
    block: Markup | None = None       # optional rich block (diff table, cron breakdown) shown instead
                                      # of the code pane; MUST be built with Markup.format()/escape()


@dataclass(frozen=True)
class Tool:
    slug: str
    title: str
    description: str
    fields: tuple
    actions: tuple
    handler: Callable                 # (action, form: dict, files: dict) -> Result
    group: str = "Tools"
    layout: str = "form"              # form | split (input/output panes) | compare | cron
    ext: str = "txt"                  # file extension for the Download button
    sample: dict | None = None        # {field_name: sample text} for the Sample button
    presets: tuple = ()               # ((label, value), ...) quick-pick chips (cron)
    live: str = ""                    # field name that re-runs the tool as the user types
    rate: str = "30 per minute"       # per-IP rate limit for the run endpoint


def clamp_int(value: str, lo: int, hi: int, label: str) -> int:
    """Parse an integer form value and require lo <= n <= hi."""
    try:
        n = int(str(value).strip())
    except ValueError:
        raise ToolError(f"{label} must be a whole number.")
    if not lo <= n <= hi:
        raise ToolError(f"{label} must be between {lo} and {hi}.")
    return n


_REGISTRY: dict[str, Tool] = {}


def register(tool: Tool) -> Tool:
    _REGISTRY[tool.slug] = tool
    return tool


def all_tools() -> list[Tool]:
    """Tools grouped by `group` (groups in first-seen order, registration order inside each)."""
    order = list(dict.fromkeys(t.group for t in _REGISTRY.values()))
    return sorted(_REGISTRY.values(), key=lambda t: order.index(t.group))


def get_tool(slug: str) -> Tool | None:
    return _REGISTRY.get(slug)
